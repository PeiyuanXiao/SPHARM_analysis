# ------------------------------------------------------------------------------
# get_rot_matrix()
# 计算将向量 a 旋转到向量 b 的旋转矩阵（Rodrigues 公式）
#
# 参数：
#   a : 起始单位向量（长度为3的数值向量）
#   b : 目标单位向量（长度为3的数值向量）
#
# 返回：
#   3×3 旋转矩阵
#
# 边界情况处理：
#   - a 与 b 方向相反（cos_theta ≈ -1）：绕垂直轴旋转180°
#   - a 与 b 方向相同（cos_theta ≈  1）：返回单位矩阵
# ------------------------------------------------------------------------------
get_rot_matrix <- function(a, b) {
  a <- a / sqrt(sum(a^2))
  b <- b / sqrt(sum(b^2))
  cos_theta <- sum(a * b)
  
  if (cos_theta < -1 + 1e-10) {
    perp <- if (abs(a[1]) < 0.9) c(1, 0, 0) else c(0, 1, 0)
    v <- perp - sum(perp * a) * a
    v <- v / sqrt(sum(v^2))
    return(2 * outer(v, v) - diag(3))
  }
  
  if (cos_theta > 1 - 1e-10) return(diag(3))
  
  v <- c(
    a[2] * b[3] - a[3] * b[2],
    a[3] * b[1] - a[1] * b[3],
    a[1] * b[2] - a[2] * b[1]
  )
  v_skew <- matrix(
    c( 0,    -v[3],  v[2],
       v[3],  0,    -v[1],
       -v[2],  v[1],  0   ),
    3, 3, byrow = TRUE
  )
  diag(3) + v_skew + v_skew %*% v_skew * ((1 - cos_theta) / sum(v^2))
}
